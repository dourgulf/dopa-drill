export function translateStaticDocument(root) {
  const walker = root.createTreeWalker(root.documentElement, 4);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.closest('#logo') || ['SCRIPT', 'STYLE'].includes(parent.tagName)) continue;
    const original = node.nodeValue;
    const key = original.trim();
    if (Object.hasOwn(STATIC_ZH_CN, key)) node.nodeValue = original.replace(key, STATIC_ZH_CN[key]);
  }
  for (const el of root.querySelectorAll('[aria-label], meta[name="description"]')) {
    const attr = el.hasAttribute('aria-label') ? 'aria-label' : 'content';
    const value = el.getAttribute(attr);
    if (Object.hasOwn(STATIC_ZH_CN, value)) el.setAttribute(attr, STATIC_ZH_CN[value]);
  }
  // Preserve the illustrated logo's SVG and per-character animation while
  // changing the visible brand text for Chinese readers.
  const top = root.querySelectorAll('#logo .logo-top i');
  const ribbon = root.querySelectorAll('#logo .logo-ribbon i');
  ['多', '巴'].forEach((char, i) => { if (top[i]) { top[i].textContent = char; top[i].dataset.c = char; } });
  ['练', '习'].forEach((char, i) => { if (ribbon[i]) ribbon[i].textContent = char; });
  if (ribbon[2]) ribbon[2].hidden = true;
}
